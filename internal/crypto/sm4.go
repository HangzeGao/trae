// sm4Cipher 实现 cipher.Block 接口
type sm4Cipher struct {
	rk [32]uint32 // 轮密钥
}

// NewSM4Cipher 创建 SM4 密码实例
func NewSM4Cipher(key []byte) (cipher.Block, error) {
	if len(key) != 16 {
		return nil, fmt.Errorf("%w: SM4 requires 16-byte key", model.ErrKeyLengthMismatch)
	}
	c := &sm4Cipher{}
	c.expandKey(key)
	return c, nil
}

func (c *sm4Cipher) BlockSize() int {
	return sm4BlockSize
}

func (c *sm4Cipher) Encrypt(dst, src []byte) {
	c.crypt(dst, src, false)
}

func (c *sm4Cipher) Decrypt(dst, src []byte) {
	c.crypt(dst, src, true)
}

// expandKey SM4 密钥扩展
func (c *sm4Cipher) expandKey(key []byte) {
	mk := [4]uint32{
		uint32(key[0])<<24 | uint32(key[1])<<16 | uint32(key[2])<<8 | uint32(key[3]),
		uint32(key[4])<<24 | uint32(key[5])<<16 | uint32(key[6])<<8 | uint32(key[7]),
		uint32(key[8])<<24 | uint32(key[9])<<16 | uint32(key[10])<<8 | uint32(key[11]),
		uint32(key[12])<<24 | uint32(key[13])<<16 | uint32(key[14])<<8 | uint32(key[15]),
	}

	k := [4]uint32{
		mk[0] ^ fk[0], mk[1] ^ fk[1], mk[2] ^ fk[2], mk[3] ^ fk[3],
	}

	for i := 0; i < 32; i++ {
		c.rk[i] = k[0] ^ sm4T(sm4Ap(k[1]^k[2]^k[3]^ck[i]))
		k[0], k[1], k[2], k[3] = k[1], k[2], k[3], k[0]^sm4T(sm4Ap(k[1]^k[2]^k[3]^ck[i]))
	}
}

// crypt SM4 加解密，decrypt 为 true 时使用逆序轮密钥
func (c *sm4Cipher) crypt(dst, src []byte, decrypt bool) {
	x := [4]uint32{
		uint32(src[0])<<24 | uint32(src[1])<<16 | uint32(src[2])<<8 | uint32(src[3]),
		uint32(src[4])<<24 | uint32(src[5])<<16 | uint32(src[6])<<8 | uint32(src[7]),
		uint32(src[8])<<24 | uint32(src[9])<<16 | uint32(src[10])<<8 | uint32(src[11]),
		uint32(src[12])<<24 | uint32(src[13])<<16 | uint32(src[14])<<8 | uint32(src[15]),
	}

	for i := 0; i < 8; i++ {
		var rk0, rk1, rk2, rk3 uint32
		if decrypt {
			rk0, rk1, rk2, rk3 = c.rk[31-4*i], c.rk[30-4*i], c.rk[29-4*i], c.rk[28-4*i]
		} else {
			rk0, rk1, rk2, rk3 = c.rk[4*i], c.rk[4*i+1], c.rk[4*i+2], c.rk[4*i+3]
		}
		x[0] = x[0] ^ sm4T(sm4Ap(x[1]^x[2]^x[3]^rk0))
		x[1] = x[1] ^ sm4T(sm4Ap(x[2]^x[3]^x[0]^rk1))
		x[2] = x[2] ^ sm4T(sm4Ap(x[3]^x[0]^x[1]^rk2))
		x[3] = x[3] ^ sm4T(sm4Ap(x[0]^x[1]^x[2]^rk3))
	}

	// 逆序输出
	putUint32(dst[0:4], x[3])
	putUint32(dst[4:8], x[2])
	putUint32(dst[8:12], x[1])
	putUint32(dst[12:16], x[0])
}

func putUint32(b []byte, v uint32) {
	b[0] = byte(v >> 24)
	b[1] = byte(v >> 16)
	b[2] = byte(v >> 8)
	b[3] = byte(v)
}

// sm4Ap SM4 非线性变换 τ 的输出经过移位后的值
func sm4Ap(a uint32) uint32 {
	return (a << 8) | (a << 20) | (a >> 24) | (a >> 12)
}

// sm4T SM4 置换变换 T = τ ∘ L
func sm4T(a uint32) uint32 {
	b := sm4Tau(a)
	return b ^ (b << 8) ^ (b << 2) ^ (b << 18) ^ ((b & 0x3f) << 26) ^ ((b >> 13) & 0x1f) ^ ((b >> 15) & 0x3)
}

// sm4Tau SM4 非线性变换 τ (S盒替换)
func sm4Tau(a uint32) uint32 {
	return uint32(sbox[a>>24])<<24 | uint32(sbox[(a>>16)&0xff])<<16 | uint32(sbox[(a>>8)&0xff])<<8 | uint32(sbox[a&0xff])
}
